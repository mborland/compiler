'''Render and check the CIR back end support table.

usage: make_support.py [--data-dir DIR] [--out-dir DIR]
       make_support.py --check [--gate M6.x] [--data-dir DIR] [--out-dir DIR]

Without --check, reads the section files (cxx.json, c.json, ...) in the
data directory (default: beside this script; the schema is in README.md)
and writes three files:

  support.md                      the full table in GitHub Markdown
  doc/source/cir_support.inc      the same, for the Sphinx chapter cir_be
  cir_src/doc/exsum/support.svg   the stacked bars of the executive summary

With --out-dir, the three files go to that directory instead.  The alt
text of the chart and the rows to mention in the slide's presenter notes
(status no and ignored) are printed on stdout.

With --check, validates the data (schema, ids, the rules of each status,
that every test and ref path exists, that e2e-run tests are in the CIR
suite or corpus and not listed as failing), that the three rendered files
are up to date, and, with --gate, the thresholds due by that gate.  Prints
the counts per group and status.  The exit status is 1 when there is an
error.
'''

