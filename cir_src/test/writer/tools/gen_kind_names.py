#!/usr/bin/env python3
"""Generate src/ecil_kind_names.h: switch tables from the enumerators of the
IL kinds the writer reports in "does not support" diagnostics (expression
nodes, operators, constants, builtin operations, statements) to their names.
Only the enumerators that exist in every configuration (not inside #if) are
listed; the others are reported by number.  Run from the repository root:
  python3 cir_src/test/writer/tools/gen_kind_names.py > src/ecil_kind_names.h
"""
import re
import sys

text = open('src/il_def.h').read()
friendly = {
  'enk_throw': 'throw expression', 'enk_typeid': 'typeid expression',
  'enk_new_delete': 'new or delete expression',
  'enk_lambda': 'lambda expression', 'enk_await': 'co_await expression',
  'enk_yield': 'co_yield expression', 'enk_fold': 'fold expression',
  'enk_requires': 'requires expression',
  'eok_spaceship': 'three-way comparison (<=>)',
  'eok_dynamic_cast': 'dynamic_cast', 'eok_ref_dynamic_cast':
  'dynamic_cast to a reference', 'eok_dot_pm_call':
  'call through a pointer to member (.*)', 'eok_points_to_pm_call':
  'call through a pointer to member (->*)', 'eok_pm_field':
  'pointer-to-data-member selection (.*)', 'eok_pm_points_to_field':
  'pointer-to-data-member selection (->*)', 'eok_bassign': 'block assignment',
  'eok_virtual_function_ptr': 'virtual function pointer',
  'eok_dot_pm_func_ptr': 'pointer to member function selection (.*)',
  'eok_points_to_pm_func_ptr': 'pointer to member function selection (->*)',
  'eok_vector_question': 'vector ?:', 'eok_splice': 'reflection splice',
  'ck_ptr_to_member': 'pointer-to-member constant', 'ck_void': 'void constant',
  'ck_reflection': 'reflection constant', 'ck_template_param':
  'template parameter constant',
  'bok_builtin_shuffle': '__builtin_shuffle', 'bok_builtin_shufflevector':
  '__builtin_shufflevector', 'bok_builtin_convertvector':
  '__builtin_convertvector', 'bok_builtin_addressof': '__builtin_addressof',
  'bok_builtin_bit_cast': '__builtin_bit_cast', 'bok_builtin_complex':
  '__builtin_complex', 'bok_builtin_has_attribute':
  '__builtin_has_attribute',
  'stmk_try_block': 'try statement', 'stmk_coroutine': 'coroutine statement',
  'stmk_coroutine_return': 'co_return statement', 'stmk_asm':
  'asm statement', 'stmk_set_vla_size': 'variable length array size',
  'stmk_vla_decl': 'variable length array declaration',
  }

def unconditional(enum, prefix):
  i = text.index(enum)
  j = text.index('};', i)
  depth = 0
  names = []
  for line in text[i:j].split('\n'):
    s = line.strip()
    if re.match(r'#\s*(if|ifdef|ifndef)\b', s):
      depth += 1
    elif re.match(r'#\s*endif', s):
      depth -= 1
    elif depth == 0:
      m = re.match(r'(%s\w+)\s*(,|/\*|$)' % prefix, s)
      if m and not m.group(1).endswith('_last'):
        names.append(m.group(1))
  return names

tables = [
  ('ecil_expr_kind_name', 'enum an_expr_node_kind', 'enk_',
   'an expression node kind'),
  ('ecil_operator_name', 'enum an_expr_operator_kind', 'eok_',
   'an expression operator kind'),
  ('ecil_constant_kind_name', 'enum a_constant_repr_kind', 'ck_',
   'a constant kind'),
  ('ecil_builtin_operation_name', 'enum a_builtin_operation_kind', 'bok_',
   'a built-in operation kind'),
  ('ecil_statement_kind_name', 'enum a_statement_kind', 'stmk_',
   'a statement kind'),
]
out = sys.stdout
out.write('/* Generated by cir_src/test/writer/tools/gen_kind_names.py from\n'
          '   il_def.h: do not edit.  Names of IL kinds for diagnostics. */\n\n')
for fn, enum, prefix, what in tables:
  out.write('const char *%s(int kind)\n/*\nReturn the name of %s for '
            'a diagnostic, or NULL if it\nhas none here.\n*/\n'
            '{\n  const char  *name = NULL;\n\n  switch (kind) {\n'
            % (fn, what))
  for n in unconditional(enum, prefix):
    label = friendly.get(n, n[len(prefix):].replace('_', ' '))
    out.write('    case %s:\n      name = "%s";\n      break;\n' % (n, label))
  out.write('    default: break;\n  }  /* switch */\n  return name;\n}'
            '  /* %s */\n\n' % fn)
