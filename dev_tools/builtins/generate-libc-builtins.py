'''Generate src/builtin_libc.h: the C library functions that are builtins.

The CIR back end turns a call of __builtin_X into an ordinary call of X when
X is a C library function (libc or libm) whose builtin form means exactly that
call.  This script derives that set of names from the same builtins_*.txt
scrapes as generate-builtin-table.py, which it does not use and does not
change (src/builtin_defs.h and src/builtin_kinds.h are not regenerated by it).

The rule.  A name X is a library function builtin if, in every scrape file
(compiler, version, architecture, word size) that lists both __builtin_X and
X (as plain, unqualified names), the two have the same signature once
noexcept/throw(), attributes and restrict qualifiers are ignored, and X is
not excluded.  Both GCC and Clang list a function under both spellings only
if it is a library function with builtin semantics (DEF_LIB_BUILTIN in GCC,
LIBBUILTIN in Clang); that is the necessary condition the data gives.  It is
not sufficient: the data also pairs names that are compiler intrinsics,
type-generic macros and runtime-internal entries with a plain twin.  The
exclusions below remove those; each has its reason.

The output is a header with one array, builtin_libc_names, sorted by strcmp
and ended by a NULL, and its length, num_builtin_libc_names.

Usage:
  generate-libc-builtins.py [-o src/builtin_libc.h] [--builtins-dir DIR]
                            [--report]

--builtins-dir defaults to the directory of this script.  Without -o the
header goes to stdout.  --report prints the size of the derived set and the
exclusions applied, to stderr.
'''

import argparse
import re
import sys

from pathlib import Path
from typing import Dict, List, Set, Tuple

# Scrape lines: "/* qualified-name */ declaration;".
_LINE_REGEX = re.compile(r'/\* (\S+) \*/ (.*)$')

_FP_SUFFIXES = ('', 'f', 'l')


def with_fp_suffixes(bases: List[str]) -> Set[str]:
  '''The names of bases with the float and long double suffixes.'''
  return {base + suffix for base in bases for suffix in _FP_SUFFIXES}


# The exclusions: (reason, names).  A name that is excluded for several
# reasons is listed under the first.
_COMPLEX_BASES = [
  'cabs', 'carg', 'cimag', 'creal', 'conj', 'cproj', 'cexp', 'clog',
  'clog10', 'cpow', 'csqrt', 'csin', 'ccos', 'ctan', 'csinh', 'ccosh',
  'ctanh', 'casin', 'cacos', 'catan', 'casinh', 'cacosh', 'catanh'
]
_DECIMAL_BASES = ['fabs', 'finite', 'isinf', 'isnan', 'nan', 'signbit']
_C23_MATH_BASES = [
  'acospi', 'asinpi', 'atan2pi', 'atanpi', 'cospi', 'sinpi', 'tanpi',
  'fmaximum_num', 'fminimum_num'
]

EXCLUSIONS: List[Tuple[str, Set[str]]] = [
  ('compiler intrinsic with its own semantics (variable argument lists, '
   'stack allocation, address-of, coroutines): not a call of a library '
   'function',
   {'va_start', 'va_end', 'va_copy', 'alloca', 'addressof', 'coro_destroy',
    'coro_done', 'coro_promise', 'coro_resume'}),
  ('type-generic classification: the builtin accepts every floating type, '
   'the C library function (if any) only double; the front end has a '
   'special translation for these',
   with_fp_suffixes(['isnan', 'isinf', 'finite', 'signbit'])),
  ('decimal floating point: the types are not supported and no C library '
   'has the functions',
   {base + size for base in _DECIMAL_BASES
    for size in ('d32', 'd64', 'd128', 'd64x')}),
  ('complex arguments and results: not supported by the CIR back end yet '
   '(the call would be diagnosed anyway); revisit with complex support',
   with_fp_suffixes(_COMPLEX_BASES)),
  ('memory protection extensions (MPX) bounds checker: compiler runtime, '
   'not C library functions',
   {'__bnd_chk_ptr_bounds', '__bnd_chk_ptr_lbounds', '__bnd_chk_ptr_ubounds',
    '__bnd_copy_ptr_bounds', '__bnd_get_ptr_lbound', '__bnd_get_ptr_ubound',
    '__bnd_init_ptr_bounds', '__bnd_narrow_ptr_bounds',
    '__bnd_null_ptr_bounds', '__bnd_set_ptr_bounds', '__bnd_store_ptr_bounds',
    '__chkp_bndcl', '__chkp_bndcu', '__chkp_bndldx', '__chkp_bndmk',
    '__chkp_bndret', '__chkp_bndstx', '__chkp_extract_lower',
    '__chkp_extract_upper'} |
   {f"chkp_{base}{variant}"
    for base in ('memcpy', 'memmove', 'mempcpy', 'memset')
    for variant in ('_nobnd', '_nobnd_nochk', '_nochk')}),
  ('libgcc entry points used for code generation (emulated TLS, nested '
   'function trampolines), not for source calls',
   {'__emutls_get_address', '__emutls_register_common',
    '__gcc_nested_func_ptr_created', '__gcc_nested_func_ptr_deleted'}),
  ('functions of C23 and later that glibc has only from version 2.41 (the '
   'trigonometric pi functions, fmaximum_num, fminimum_num) or 2.42 (uabs '
   'and its relatives), or never (ffsimax): the compilers expand them '
   'inline, a call would not link on older systems',
   with_fp_suffixes(_C23_MATH_BASES) |
   {'uabs', 'ulabs', 'ullabs', 'umaxabs', 'uimaxabs', 'ffsimax'}),
  ('listed by the compilers, but not exported by glibc (checked against '
   'glibc 2.42), or only as a compatibility symbol that new programs cannot '
   'link to (pow10 was removed in glibc 2.27)',
   {'gamma_r', 'gammaf_r', 'gammal_r', 'printf_unlocked',
    'fprintf_unlocked', 'puts_unlocked', 'pow10', 'pow10f', 'pow10l'})
]


def normalize_signature(declaration: str, name: str) -> str:
  '''The declaration with its name replaced, without what does not matter.

  The scrapes of GCC print `type name(params)`, those of Clang
  `type (name)(params) noexcept`; exception specifications, attributes and
  restrict qualifiers are not part of the comparison.
  '''
  text = declaration.strip().rstrip(';')
  if f"({name})" in text:
    text = text.replace(f"({name})", '@')
  else:
    text = text.replace(name, '@', 1)
  text = re.sub(r'\b(noexcept|throw\(\))', '', text)
  text = re.sub(r'__attribute__\(\(\w+\)\)', '', text)
  text = re.sub(r'\b(__restrict|restrict)\b', '', text)
  return re.sub(r'\s+', '', text)


def read_scrape(path: Path) -> Dict[str, str]:
  '''The plain (not header-qualified) names of a scrape file with their
  declarations.'''
  entries: Dict[str, str] = {}
  for line in path.read_text(errors = 'replace').splitlines():
    match = _LINE_REGEX.match(line)
    if match and ':' not in match.group(1):
      entries[match.group(1)] = match.group(2)
  return entries


def derive_twins(files: List[Path]) -> Set[str]:
  '''The names X that have an identical X and __builtin_X in every scrape
  that lists both.'''
  agree: Set[str] = set()
  disagree: Set[str] = set()
  for path in files:
    entries = read_scrape(path)
    for builtin, declaration in entries.items():
      if not builtin.startswith('__builtin_'):
        continue
      name = builtin[len('__builtin_'):]
      if name not in entries:
        continue
      if (normalize_signature(declaration, builtin) ==
          normalize_signature(entries[name], name)):
        agree.add(name)
      else:
        disagree.add(name)
  return agree - disagree


def format_header(names: List[str], scrape_count: int) -> str:
  '''The text of src/builtin_libc.h.'''
  lines = []
  current = ' '
  for name in names:
    item = f' "{name}",'
    if len(current) + len(item) > 79:
      lines.append(current)
      current = ' '
    current += item
  lines.append(current)
  body = '\n'.join(lines)
  return f'''/*
Part of the EDG Compiler Project, under the Apache License v2.0 with LLVM
Exceptions.
See https://edgcpp.org/LICENSE.txt for license information.
SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception
*/

/*

builtin_libc.h -- The C library functions that are also builtins

*/

/* Conditionally open the "edg" namespace. */
BEGIN_EDG_NAMESPACE

/*------------------Beginning of automatically generated code---------------*/
/* Generated by dev_tools/builtins/generate-libc-builtins.py from the
{scrape_count} builtins_*.txt scrape files; do not edit.  See that script for
the rule and the exclusions. */

/*
The names X of the C library functions (libc and libm) for which a call of
__builtin_X can be translated to a call of X itself.  Sorted by strcmp and
terminated by a NULL; num_builtin_libc_names is the number of names before it.
*/
static constexpr const char* const
                builtin_libc_names[] = {{
{body}
  NULL
}};

static constexpr size_t
                num_builtin_libc_names =
                        /* Number of names in builtin_libc_names. */
        sizeof(builtin_libc_names)/sizeof(builtin_libc_names[0]) - 1;

/*--------------------End of automatically generated code-----------------*/

/* Conditionally close the "edg" namespace. */
END_EDG_NAMESPACE
'''


def main() -> None:
  parser = argparse.ArgumentParser(description = __doc__.split('\n')[0])
  parser.add_argument('-o', dest = 'output', default = '',
                      help = 'write the header here (default: stdout)')
  parser.add_argument('--builtins-dir',
                      default = str(Path(__file__).resolve().parent))
  parser.add_argument('--report', action = 'store_true',
                      help = 'print the size of the set and the exclusions '
                             'to stderr')
  args = parser.parse_args()

  files = sorted(Path(args.builtins_dir).glob('builtins_*.txt'))
  if not files:
    sys.exit(f"no builtins_*.txt files in {args.builtins_dir}")
  twins = derive_twins(files)
  excluded: Set[str] = set()
  for _, names in EXCLUSIONS:
    excluded |= names
  result = sorted(twins - excluded)

  if args.report:
    print(f"{len(files)} scrape files; {len(twins)} names have an identical "
          f"plain twin; {len(twins & excluded)} excluded; "
          f"{len(result)} in the set", file = sys.stderr)
    for reason, names in EXCLUSIONS:
      applied = sorted(twins & names)
      print(f"excluded ({len(applied)}): {reason}\n  {' '.join(applied)}",
            file = sys.stderr)
    unused = sorted(excluded - twins)
    if unused:
      print(f"exclusion names without a twin in the data: {' '.join(unused)}",
            file = sys.stderr)

  text = format_header(result, len(files))
  if args.output:
    Path(args.output).write_text(text)
  else:
    sys.stdout.write(text)


if __name__ == '__main__':
  main()
