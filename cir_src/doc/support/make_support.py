class Report:
  '''The errors and warnings found by --check.'''

  def __init__(self) -> None:
    self.errors: List[str] = []
    self.warnings: List[str] = []

  def error(self, where: str, message: str) -> None:
    self.errors.append(f"{where}: {message}")

  def warn(self, where: str, message: str) -> None:
    self.warnings.append(f"{where}: {message}")


def load_sections(data_dir: Path, report: Report) -> List[Dict]:
  '''Read the section files that exist, in document order.'''
  sections = []
  for name in SECTIONS:
    path = data_dir / f"{name}.json"
    if not path.exists():
      report.error(f"{name}.json", 'missing')
      continue
    try:
      data = json.loads(path.read_text(encoding = 'utf-8'))
    except (OSError, ValueError) as error:
      report.error(f"{name}.json", f"cannot read: {error}")
      continue
    if not isinstance(data, dict):
      report.error(f"{name}.json", 'the top level must be an object')
      continue
    sections.append(data)
  return sections


# Validation ------------------------------------------------------------


def gate_rank(gate: str) -> int:
  return GATES.index(gate)


def is_text(value: object, *, empty_ok: bool = False) -> bool:
  return isinstance(value, str) and (empty_ok or value.strip() != '')


def check_keys(where: str, obj: Dict, allowed: frozenset,
               report: Report) -> None:
  for key in sorted(set(obj) - allowed):
    report.error(where, f"unknown key '{key}'")


def parse_filter_file(path: Path) -> Tuple[List[Tuple[str, str]],
                                           List[Tuple[str, str]]]:
  '''Split an edgy filter file into (suite, prefix) positives and
  negatives, as edgy's _construct_prefix_filter does.'''
  positive: List[Tuple[str, str]] = []
  negative: List[Tuple[str, str]] = []
  for line in path.read_text(encoding = 'utf-8').splitlines():
    line = line.strip()
    if line == '' or line.startswith('#'):
      continue
    excluded = line.startswith('!')
    parts = (line[1:] if excluded else line).split('/')
    if len(parts) > 1:
      (negative if excluded else positive).append(
        (parts[0], '/'.join(parts[1:]))
      )
  return positive, negative


class Evidence:
  '''The CIR suite, the corpus filters and the expectation logs.'''

  def __init__(self) -> None:
    self.filters = []
    for name in CORPUS_FILTERS:
      path = FILTERS / name
      if path.exists():
        self.filters.append(parse_filter_file(path))
    self.failing: Dict[str, Set[str]] = {}
    self.reference: Dict[str, Set[str]] = {}

  def in_corpus(self, suite: str, rel_path: str) -> bool:
    '''Whether a test of the suite is in the CIR suite or in a corpus.'''
    if suite == 'cir':
      return True
    for positive, negative in self.filters:
      if (any(s == suite and rel_path.startswith(p) for s, p in positive)
          and not any(s == suite and rel_path.startswith(p)
                      for s, p in negative)):
        return True
    return False

  def is_failing(self, suite: str, rel_path: str) -> bool:
    '''Whether the CIR expectation log of the suite lists the test.'''
    if suite not in self.failing:
      listed = set()
      log = EXPECTATIONS / f"{suite}.log"
      if log.exists():
        for line in log.read_text(encoding = 'utf-8').splitlines():
          listed.add(line.split(':', 1)[0])
      self.failing[suite] = listed
    return rel_path in self.failing[suite]

  def is_reference_failing(self, suite: str, rel_path: str) -> bool:
    '''Whether the reference (edg_x86_64) log of the suite lists the
    test.'''
    if suite not in self.reference:
      listed = set()
      log = REFERENCE / f"{suite}.log"
      if log.exists():
        for line in log.read_text(encoding = 'utf-8').splitlines():
          listed.add(line.split(':', 1)[0])
      self.reference[suite] = listed
    return rel_path in self.reference[suite]


def read_directives(path: Path) -> Dict[str, List[str]]:
  '''The //key:value directive block of a test, as edgutil's
  collect_cpp_line_directives reads it.'''
  directives: Dict[str, List[str]] = {}
  started = False
  with path.open(encoding = 'utf-8', errors = 'backslashreplace') as handle:
    for line in handle:
      match = DIRECTIVE.match(line)
      if match is None:
        if started:
          break
        continue
      started = True
      directives.setdefault(match.group(1), []).append(match.group(2))
  return directives


def option_mode(options: List[str], language: str,
                gnu_version: int) -> Optional[int]:
  '''The language standard (a year) that a list of options selects for
  the language ("c" or "cpp"), or the configuration's default.  The last
  option wins.'''
  cpp_modes = {'03': 1998, '98': 1998, '0x': 2011, '11': 2011, '14': 2014,
               '17': 2017, '1z': 2017, '20': 2020, '2a': 2020, '23': 2023,
               '2b': 2023, '26': 2026}
  c_modes = {'89': 1989, '90': 1989, '99': 1999, '11': 2011, '17': 2017,
             '18': 2017, '23': 2023, '2x': 2023}
  mode = None
  gnu_mode = gnu_version > 0
  for option in options:
    match = re.match(r'^--c\+\+(\w+)$', option)
    if match and language == 'cpp' and match.group(1) in cpp_modes:
      mode = cpp_modes[match.group(1)]
    match = re.match(r'^--c(\w+)$', option)
    if match and language == 'c' and match.group(1) in c_modes:
      mode = c_modes[match.group(1)]
    match = re.match(r'^--gnu_version=(\d+)$', option)
    if match:
      gnu_version, gnu_mode = int(match.group(1)), True
    if option in ('--gcc', '--g++'):
      gnu_mode = True
  if mode is not None:
    return mode
  # With no standard option, cmd_line.c picks the standard.  C++: the
  # cpfe-cir configuration leaves DEFAULT_CPP_MODE unset (C++03); GNU mode
  # (--g++ or --gnu_version) gives C++17 from gnu_version 110000 and C++14
  # from 60000.  C: DEFAULT_C99_MODE is FALSE (C89); GNU mode (--gcc or
  # --gnu_version) gives C23 from 150000, C17 from 80000 and C11 from
  # 50000.  DEFAULT_GNU_COMPATIBILITY is 0 on Linux.
  if language == 'cpp':
    if gnu_mode and gnu_version >= 110000:
      return 2017
    return 2014 if gnu_mode and gnu_version >= 60000 else 1998
  if gnu_mode and gnu_version >= 150000:
    return 2023
  if gnu_mode and gnu_version >= 80000:
    return 2017
  return 2011 if gnu_mode and gnu_version >= 50000 else 1989


def inherited_flags(path: Path) -> List[str]:
  '''The options_all of the .run_test_flags files above a test, up to
  tests/tests, outermost first.'''
  options: List[str] = []
  chain = []
  for directory in path.parents:
    if directory == TESTS or TESTS not in directory.parents:
      break
    chain.append(directory)
  for directory in reversed(chain):
    flags = directory / '.run_test_flags'
    if flags.exists():
      for value in read_directives(flags).get('options_all', []):
        options.extend(shlex.split(value))
  return options


def test_mode(path: Path, directives: Dict[str, List[str]]
              ) -> Tuple[str, Optional[int]]:
  '''The language ("c" or "cpp") and the lowest language standard of
  the cases of a test.'''
  options = inherited_flags(path)
  for value in directives.get('options_all', []):
    options.extend(shlex.split(value))
  separator = (directives.get('options_sep') or [':'])[0] or ':'
  cases = []
  for value in directives.get('options', ['']):
    for case in value.split(separator):
      match = CASE_TYPE.match(case)
      cases.append(shlex.split(match.group(1) if match else case))
  language = 'c' if path.suffix == '.c' else 'cpp'
  modes = [option_mode(options + case, language, 0) for case in cases]
  return language, min(modes) if modes else None


def ref_path(ref: str) -> Tuple[Optional[Path], Optional[int]]:
  '''The file and the line a ref names, or None for the file when it does
  not exist.'''
  match = REF_PATTERN.match(ref)
  if match is None:
    return None, None
  name = match.group(1)
  line = int(match.group(2)) if match.group(2) else None
  # Doc refs may be relative to cir_src/ ("doc/project.md §4") or to
  # cir_src/doc/ ("project.md §4").
  candidates = [ROOT / name, ROOT / 'cir_src' / name,
                ROOT / 'cir_src' / 'doc' / name]
  for candidate in candidates:
    if candidate.exists():
      return candidate, line
  return None, line


def check_test(where: str, test: object, evidence: Evidence,
               report: Report) -> Optional[Dict]:
  '''Validate one tests entry and return its kind, language and language
  standard (for an e2e-run test) when the kind is valid.'''
  if not isinstance(test, dict):
    report.error(where, 'a test must be an object with path and kind')
    return None
  check_keys(where, test, frozenset(('path', 'kind')), report)
  path, kind = test.get('path'), test.get('kind')
  if kind not in KINDS:
    report.error(where, f"kind '{kind}' is not one of {', '.join(KINDS)}")
    return None
  info: Dict = {'kind': kind, 'path': path, 'language': None, 'mode': None,
                'valid': True}
  if not is_text(path):
    report.error(where, 'a test needs a path')
    return info
  if not (ROOT / path).exists():
    report.error(where, f"test path '{path}' does not exist")
    info['valid'] = False
    return info
  parts = Path(path).parts
  in_tests = parts[:2] == ('tests', 'tests') and len(parts) > 3
  suite = parts[2] if in_tests else ''
  rel_path = '/'.join(parts[3:]) if in_tests else ''
  log = f"tests/expectations/edg_x86_64_cir/{suite}.log"
  if kind == 'e2e-run' and path.startswith(MIXED_TU_DIR):
    pass
  elif kind == 'e2e-run':
    check_e2e_run(where, path, in_tests, suite, rel_path, log, evidence,
                  report, info)
  elif kind == 'failing':
    if not in_tests:
      report.error(where, f"failing test '{path}' must be under "
                          'tests/tests/<suite>/')
    elif not evidence.is_failing(suite, rel_path):
      report.error(where, f"failing test '{path}' is not listed as "
                          f"failing in {log}")
    elif evidence.is_reference_failing(suite, rel_path):
      report.error(where, f"failing test '{path}' also fails in the "
                          'reference (tests/expectations/edg_x86_64/'
                          f"{suite}.log): a front-end or test problem")
  elif kind == 'negative':
    if not path.startswith(NEGATIVE_DIRS):
      report.error(where, f"negative test '{path}' must be under "
                          f"{' or '.join(NEGATIVE_DIRS)}")
    elif Path(path).name.startswith('bad-'):
      report.error(where, f"negative test '{path}' is a bad-* test of "
                          'malformed ECIL, which does not count')
  return info


def check_e2e_run(where: str, path: str, in_tests: bool, suite: str,
                  rel_path: str, log: str, evidence: Evidence,
                  report: Report, info: Dict) -> None:
  '''The rules of an e2e-run test; sets info's language and mode.'''
  if not in_tests:
    report.error(where, f"e2e-run test '{path}' must be under "
                        'tests/tests/<suite>/')
    return
  directives = read_directives(ROOT / path)
  test_type = (directives.get('type') or [''])[0].strip()
  if test_type != 'rp':
    report.error(where, f"e2e-run test '{path}' has //type:{test_type}, "
                        'not rp (compile, link and run)')
  if 'script' in directives:
    report.error(where, f"e2e-run test '{path}' has a //script: line")
  if not evidence.in_corpus(suite, rel_path):
    report.error(where, f"e2e-run test '{path}' is in neither the CIR "
                        'suite nor a CIR corpus filter')
  elif evidence.is_failing(suite, rel_path):
    report.error(where, f"e2e-run test '{path}' is listed as failing in "
                        f"{log}")
  info['language'], info['mode'] = test_mode(ROOT / path, directives)


def is_code_ref(ref: str) -> bool:
  '''Whether a ref is path:line into the code (not a document).'''
  match = REF_PATTERN.match(ref)
  return (match is not None and match.group(2) is not None
          and match.group(1).startswith(CODE_REF_DIRS))


def check_mode(where: str, row: Dict, group_id: str, tests: List[Dict],
               gate: str, report: Report) -> None:
  '''A yes row of a standard's group needs an e2e-run test in that
  standard or later, unless mode_independent.'''
  match = GROUP_MODE.match(group_id)
  if match is None or row.get('mode_independent'):
    return
  language = 'cpp' if match.group(1) == 'cxx' else 'c'
  number = int(match.group(2))
  year = 1900 + number if number >= 50 else 2000 + number
  if any(t['kind'] == 'e2e-run' and t['language'] == language
         and t['mode'] is not None and t['mode'] >= year for t in tests):
    return
  message = (f"status yes in group {group_id} needs an e2e-run test in "
             f"{'C++' if language == 'cpp' else 'C'} mode {year} or "
             'later (or mode_independent); the checker warns until M6.1a')
  if gate_rank(gate) >= gate_rank('M6.1a'):
    report.error(where, message)
  else:
    report.warn(where, message)


def check_status_rules(where: str, row: Dict, group_id: str,
                       tests: List[Dict], gate: str,
                       report: Report) -> None:
  '''The per-status rules of README.md.'''
  status = row['status']
  note, planned = row.get('note'), row.get('planned')
  kinds = [t['kind'] for t in tests]
  strict = gate_rank(gate) >= gate_rank('M6.1a')
  if status in ('yes', 'partial'):
    if row.get('since') is None:
      report.error(where, f"status {status} needs since")
    if 'e2e-run' not in kinds:
      report.error(where, f"status {status} needs an e2e-run test")
    if planned is not None and status == 'yes':
      report.warn(where, 'planned is set on a yes row')
  else:
    if row.get('since') is not None:
      report.warn(where, f"since is set on a {status} row")
    if planned is None:
      report.error(where, f"status {status} needs planned")
    elif status == 'unverified' and planned != 'M6.1a':
      report.warn(where, f"unverified row planned {planned}, after M6.1a "
                         '(it must be resolved by M6.1a)')
    elif (planned.startswith('M6.') and planned in GATES
          and gate_rank(planned) < gate_rank(gate)):
      report.warn(where, f"planned {planned} is before the gate {gate}")
  if 'failing' in kinds and status not in ('no', 'partial'):
    report.error(where, f"a failing test cannot support a {status} row "
                        '(only no and partial)')
  if status == 'yes':
    check_mode(where, row, group_id, tests, gate, report)
  if status == 'partial' and not is_text(note):
    report.error(where, 'status partial needs a note naming the residue')
  if status in ('no', 'partial') and 'negative' not in kinds:
    message = (f"status {status} needs a negative test (the checker warns "
               'until M6.1a)')
    if strict:
      report.error(where, message)
    else:
      report.warn(where, message)
  if status == 'no' and 'failing' not in kinds:
    if not any(is_code_ref(ref) for ref in row.get('refs') or []):
      report.error(where, 'status no needs a refs entry path:line into '
                          f"{', '.join(CODE_REF_DIRS)} naming the diagnose "
                          'site, or a failing test')
  if status == 'unverified' and strict:
    report.error(where, f"status unverified is not allowed from M6.1a "
                        f"(gate {gate})")
  if status == 'ignored' and gate_rank(gate) >= gate_rank('M6.4a'):
    report.error(where, f"status ignored is not allowed from M6.4a "
                        f"(gate {gate})")


def check_row(where: str, row: object, group_id: str, seen: Dict[str, str],
              seen_macros: Dict[Tuple[str, str], str], evidence: Evidence,
              gate: str, report: Report) -> None:
  if not isinstance(row, dict):
    report.error(where, 'a row must be an object')
    return
  row_id = row.get('id')
  where = f"{where}/{row_id}"
  check_keys(where, row, ROW_KEYS, report)
  if not is_text(row_id) or ID_PATTERN.match(row_id) is None:
    report.error(where, f"id '{row_id}' does not match "
                        '[a-z0-9_]+\\.[a-z0-9_]+')
  else:
    if row_id.split('.')[0] != group_id:
      report.error(where, f"id does not start with the group id "
                          f"'{group_id}.'")
    if row_id in seen:
      report.error(where, f"duplicate id (also in {seen[row_id]})")
    seen[row_id] = where
  for key in ('feature',):
    if not is_text(row.get(key)):
      report.error(where, f"{key} must be a non-empty string")
  papers = row.get('papers')
  if (not isinstance(papers, list)
      or not all(is_text(paper) for paper in papers)):
    report.error(where, 'papers must be a list of strings (may be empty)')
  macro = row.get('macro')
  if macro is not None and not is_text(macro):
    report.error(where, 'macro must be null or a string')
  if macro is not None and not is_text(row.get('macro_value')):
    report.error(where, 'macro_value is required when macro is set')
  if macro is None and row.get('macro_value') is not None:
    report.error(where, 'macro_value is set without macro')
  if is_text(macro) and is_text(row.get('macro_value')):
    pair = (macro, row['macro_value'])
    if pair in seen_macros:
      report.error(where, f"duplicate macro {macro} = "
                          f"{row['macro_value']} (also in "
                          f"{seen_macros[pair]})")
    seen_macros[pair] = where
  if (row.get('mode_independent') is not None
      and not isinstance(row['mode_independent'], bool)):
    report.error(where, 'mode_independent must be true or false')
  for key in ('note',):
    if key in row and not is_text(row[key], empty_ok = True):
      report.error(where, f"{key} must be a string")
  status = row.get('status')
  if status not in STATUSES:
    report.error(where, f"status '{status}' is not one of "
                        f"{', '.join(STATUSES)}")
  since, planned = row.get('since'), row.get('planned')
  if since is not None and since not in SINCE_VALUES:
    report.error(where, f"since '{since}' is not a known gate")
  if planned is not None and planned not in PLANNED_VALUES:
    report.error(where, f"planned '{planned}' is not a known gate, M7, "
                        'after M7 or Ext')
  tests = row.get('tests', [])
  infos: List[Dict] = []
  if not isinstance(tests, list):
    report.error(where, 'tests must be a list')
  else:
    for test in tests:
      info = check_test(where, test, evidence, report)
      if info is not None:
        infos.append(info)
  refs = row.get('refs', [])
  if not isinstance(refs, list) or not all(is_text(r) for r in refs):
    report.error(where, 'refs must be a list of strings')
  else:
    for ref in refs:
      path, line = ref_path(ref)
      if path is None:
        report.error(where, f"ref '{ref}' names no existing file")
      elif line is not None and path.is_file():
        length = len(path.read_text(encoding = 'utf-8',
                                    errors = 'replace').splitlines())
        if line > length:
          report.warn(where, f"ref '{ref}' is past the end of the file "
                             f"({length} lines)")
  if status in STATUSES:
    check_status_rules(where, row, group_id, infos, gate, report)


def check_section(name: str, data: Dict, seen_rows: Dict[str, str],
                  seen_groups: Dict[str, str],
                  seen_macros: Dict[Tuple[str, str], str],
                  evidence: Evidence, gate: str, report: Report) -> None:
  where = f"{name}.json"
  check_keys(where, data, SECTION_KEYS, report)
  if data.get('schema') != 1:
    report.error(where, 'schema must be 1')
  if data.get('section') != name:
    report.error(where, f"section must be '{name}'")
  if not is_text(data.get('title')):
    report.error(where, 'title must be a non-empty string')
  if not is_text(data.get('intro'), empty_ok = True):
    report.error(where, 'intro must be a string')
  groups = data.get('groups')
  if not isinstance(groups, list):
    report.error(where, 'groups must be a list')
    return
  for group in groups:
    if not isinstance(group, dict):
      report.error(where, 'a group must be an object')
      continue
    group_id = group.get('id')
    group_where = f"{where}/{group_id}"
    check_keys(group_where, group, GROUP_KEYS, report)
    if not is_text(group_id) or GROUP_ID_PATTERN.match(group_id) is None:
      report.error(group_where, f"group id '{group_id}' does not match "
                                '[a-z0-9_]+')
      group_id = ''
    elif group_id in seen_groups:
      report.error(group_where,
                   f"duplicate group id (also in {seen_groups[group_id]})")
    else:
      seen_groups[group_id] = where
    if not is_text(group.get('title')):
      report.error(group_where, 'title must be a non-empty string')
    rows = group.get('rows')
    if not isinstance(rows, list):
      report.error(group_where, 'rows must be a list')
      continue
    for row in rows:
      check_row(group_where, row, group_id, seen_rows, seen_macros,
                evidence, gate, report)


def check_data(sections: List[Dict], gate: str, report: Report) -> None:
  evidence = Evidence()
  seen_rows: Dict[str, str] = {}
  seen_groups: Dict[str, str] = {}
  seen_macros: Dict[Tuple[str, str], str] = {}
  for data in sections:
    name = data.get('section')
    if name not in SECTIONS:
      report.error('data', f"unknown section '{name}'")
      continue
    check_section(name, data, seen_rows, seen_groups, seen_macros,
                  evidence, gate, report)


# Counting --------------------------------------------------------------


def group_counts(group: Dict) -> Dict[str, int]:
  counts = {status: 0 for status in STATUSES}
  for row in group['rows']:
    counts[row['status']] += 1
  return counts


def all_groups(sections: List[Dict]) -> List[Tuple[Dict, Dict]]:
  return [(section, group) for section in sections
          for group in section['groups']]


def total_counts(sections: List[Dict]) -> Dict[str, int]:
  totals = {status: 0 for status in STATUSES}
  for _, group in all_groups(sections):
    for status, count in group_counts(group).items():
      totals[status] += count
  return totals


def format_counts(sections: List[Dict]) -> List[str]:
  '''The counts per group and status, as aligned text lines.'''
  header = ['group'] + [LABELS[status] for status in STATUSES] + ['total']
  rows = [header]
  for section in sections:
    for group in section['groups']:
      counts = group_counts(group)
      rows.append([group['id']] + [str(counts[s]) for s in STATUSES] +
                  [str(len(group['rows']))])
  totals = total_counts(sections)
  rows.append(['TOTAL'] + [str(totals[s]) for s in STATUSES] +
              [str(sum(totals.values()))])
  widths = [max(len(row[col]) for row in rows) for col in range(len(header))]
  lines = []
  for row in rows:
    lines.append('  '.join(
      cell.ljust(widths[0]) if col == 0 else cell.rjust(widths[col])
      for col, cell in enumerate(row)
    ))
  return lines


# Cell and text formatting ----------------------------------------------

CODE_SPAN = re.compile(r'(`[^`]+`)')


def escape_plain(content: str, flavor: str) -> str:
  '''Escape the markup characters of plain text.'''
  content = content.replace('\\', '\\\\').replace('*', '\\*')
  content = content.replace('|', '\\|')
  # An underscore can only mean markup at the edge of a word.
  content = re.sub(r'(?<![A-Za-z0-9])_|_(?![A-Za-z0-9])', r'\\_', content)
  if flavor == 'md':
    content = (content.replace('<', '\\<').replace('[', '\\[')
               .replace(']', '\\]'))
  else:
    content = content.replace('`', '\\`')
  return content


def format_text(content: str, flavor: str) -> str:
  '''Plain text with `code` spans, for one table cell.'''
  content = ' '.join(content.split())
  pieces = []
  for piece in CODE_SPAN.split(content):
    if CODE_SPAN.fullmatch(piece):
      code = piece[1:-1]
      if flavor == 'md':
        pieces.append(f"`{code.replace('|', chr(92) + '|')}`")
      else:
        pieces.append(f"``{code}``")
    else:
      pieces.append(escape_plain(piece, flavor))
  return ''.join(pieces)


def macro_text(row: Dict, flavor: str) -> str:
  if row.get('macro') is None:
    return ''
  code = row['macro']
  if flavor == 'md':
    return f"`{code}` ({row['macro_value']})"
  return f"``{code}`` ({row['macro_value']})"


def cell_detail(row: Dict) -> str:
  '''The gate after the status label: since or planned.'''
  if row['status'] in ('yes', 'partial'):
    return row.get('since') or ''
  return row.get('planned') or ''


def cir_cell(row: Dict, flavor: str) -> str:
  label = LABELS[row['status']]
  detail = cell_detail(row)
  if flavor == 'md':
    text = f"**{label}**" if row['status'] == 'yes' else label
  else:
    text = f":sup-{row['status']}:`{label}`"
  return f"{text} · {detail}" if detail else text


def notes_text(row: Dict, flavor: str) -> str:
  note = format_text(row.get('note') or '', flavor)
  if row['status'] == 'partial' and row.get('planned'):
    note = f"{note} Complete in {row['planned']}.".strip()
  return note


def papers_text(row: Dict, flavor: str) -> str:
  return format_text(', '.join(row['papers']), flavor)


# support.md ------------------------------------------------------------


def render_md(sections: List[Dict]) -> str:
  totals = total_counts(sections)
  lines = [
    '# CIR back end support table', '', f"*{GENERATED}*", '',
    'What the ClangIR (CIR) back end supports, one table per language '
    'standard or feature family.  The CIR column always carries the '
    'status as text:', ''
  ]
  for status in STATUSES:
    lines.append(f"- **{LABELS[status]}**: {MEANINGS[status]}")
  lines += ['', f"{sum(totals.values())} rows: " + ', '.join(
    f"{totals[status]} {LABELS[status]}" for status in STATUSES) + '.', '']
  for section in sections:
    lines += [f"## {format_text(section['title'], 'md')}", '']
    if section['intro'].strip():
      lines += [format_text(section['intro'], 'md'), '']
    if not section['groups']:
      lines += ['Not surveyed yet.', '']
    for group in section['groups']:
      lines += [f"### {format_text(group['title'], 'md')}", '']
      if not group['rows']:
        lines += ['Not surveyed yet.', '']
        continue
      lines += ['| Feature | Paper(s) | Macro (value) | CIR | Notes |',
                '| --- | --- | --- | --- | --- |']
      for row in group['rows']:
        lines.append('| ' + ' | '.join((
          format_text(row['feature'], 'md'), papers_text(row, 'md'),
          macro_text(row, 'md'), cir_cell(row, 'md'),
          notes_text(row, 'md'))) + ' |')
      lines.append('')
  return '\n'.join(lines).rstrip('\n') + '\n'


# cir_support.inc -------------------------------------------------------


def render_inc(sections: List[Dict]) -> str:
  lines = [f".. {GENERATED}", '']
  for status in STATUSES:
    lines.append(f".. role:: sup-{status}")
  totals = total_counts(sections)
  lines += ['', 'The CIR column of every table reads:', '']
  for status in STATUSES:
    lines.append(f"* :sup-{status}:`{LABELS[status]}`: {MEANINGS[status]}")
  lines += ['', f"{sum(totals.values())} rows: " + ', '.join(
    f"{totals[status]} {LABELS[status]}" for status in STATUSES) + '.', '']
  for section in sections:
    title = format_text(section['title'], 'rst')
    lines += [title, '-' * len(title), '']
    if section['intro'].strip():
      lines += [format_text(section['intro'], 'rst'), '']
    if not section['groups']:
      lines += ['Not surveyed yet.', '']
    for group in section['groups']:
      title = format_text(group['title'], 'rst')
      lines += [title, '~' * len(title), '']
      if not group['rows']:
        lines += ['Not surveyed yet.', '']
        continue
      lines += ['.. list-table::', '   :header-rows: 1',
                '   :class: cir-support',
                '   :widths: 26 12 22 14 26', '',
                '   * - Feature', '     - Paper(s)', '     - Macro (value)',
                '     - CIR', '     - Notes']
      for row in group['rows']:
        cells = (format_text(row['feature'], 'rst'),
                 papers_text(row, 'rst'), macro_text(row, 'rst'),
                 cir_cell(row, 'rst'), notes_text(row, 'rst'))
        for index, cell in enumerate(cells):
          lead = '   * -' if index == 0 else '     -'
          lines.append(f"{lead} {cell}".rstrip())
      lines.append('')
  return '\n'.join(lines).rstrip('\n') + '\n'


# support.svg -----------------------------------------------------------


def chart_items(sections: List[Dict]) -> List[Tuple[str, object, bool]]:
  '''The (kind, item, first) rows of the chart: the non-empty groups and,
  before the groups of a section that has several, its heading.  first
  marks the first row of each section.'''
  items: List[Tuple[str, object, bool]] = []
  for section in sections:
    groups = [g for g in section['groups'] if g['rows']]
    if len(groups) > 1:
      items.append(('section', section, True))
    if len(groups) == 1:
      items.append(('group', groups[0], True))
    else:
      items.extend(('group', group, False) for group in groups)
  return items


def split_columns(items: List[Tuple[str, object, bool]],
                  ) -> List[List[Tuple[str, object, bool]]]:
  '''One column, or two split at the section boundary that balances them,
  when there are more than 22 items.'''
  if len(items) <= 22:
    return [items]
  starts = [i for i, (_, _, first) in enumerate(items) if first]
  best = min(starts[1:], key = lambda i: max(i, len(items) - i))
  return [items[:best], items[best:]]


def with_title(shape: str, title: str) -> str:
  '''Add a hover title to a self-closing shape.'''
  return f"{shape[:-2]}><title>{html.escape(title)}</title></{shape[1:5]}>"


def fit_label(charts: ModuleType, title: str, total: int, size: int,
              limit: float) -> str:
  '''The label "title \u00b7 total", with the title cut to fit.'''
  tail = f" \u00b7 {total}"
  while (charts.text_width(title + tail, size) > limit
         and len(title) > 2):
    title = title[:-2].rstrip() + '\u2026'
  return title + tail


def render_svg(sections: List[Dict]) -> str:
  charts = load_charts()
  style = charts.STYLE
  items = chart_items(sections)
  columns = split_columns(items)
  size, header_size = 20, 20
  longest = max([len(f"{item['title']} · {len(item['rows'])}")
                 for kind, item, _ in items if kind == 'group'] + [1])
  gutter, left, right = 44, 8, CHART_WIDTH - 8
  column_width = (right - left - gutter * (len(columns) - 1)) / len(columns)
  label_width = min(longest * size * 0.55 + 14, column_width * 0.4)
  most = max([len(column) for column in columns] + [1])
  pitch = max(22.0, min(34.0, (CHART_SLIDE_HEIGHT - CHART_TOP - 8) / most))
  height = int(CHART_TOP + pitch * most + 8)
  body = charts.legend([(LABELS[s], COLORS[s]) for s in STATUSES], left, 30)
  body.append(charts.text(right, 30, 'Share of the rows of each group',
                          anchor = 'end', size = 18,
                          fill = style['ink_muted']))
  gap = 2
  for number, column in enumerate(columns):
    x = left + number * (column_width + gutter)
    bar_left, bar_right = x + label_width, x + column_width
    bar_height = pitch - 8
    for index, (kind, item, _) in enumerate(column):
      top = CHART_TOP + index * pitch
      middle = top + bar_height / 2
      if kind == 'section':
        body.append(charts.text(x, middle + header_size * 0.35,
                                item['title'], size = header_size,
                                weight = 'bold',
                                fill = style['ink_secondary']))
        continue
      counts = group_counts(item)
      total = len(item['rows'])
      body.append(charts.text(
        x, middle + size * 0.35,
        fit_label(charts, item['title'], total, size, label_width - 10),
        size = size))
      present = [s for s in STATUSES if counts[s] > 0]
      span = bar_right - bar_left - gap * (len(present) - 1)
      cursor = bar_left
      for position, status in enumerate(present):
        width = span * counts[status] / total
        shape = charts.bar(cursor, cursor + width, top, bar_height,
                           COLORS[status],
                           round_left = position == 0,
                           round_right = position == len(present) - 1)
        percent = 100.0 * counts[status] / total
        body.append(with_title(
          shape, f"{item['title']}: {counts[status]} {LABELS[status]} "
                 f"of {total} ({percent:.0f}%)"))
        label = str(counts[status])
        if charts.text_width(label, size) + 12 <= width:
          body.append(charts.text(
            cursor + width / 2, middle + size * 0.35, label, size = size,
            anchor = 'middle', weight = 'bold',
            fill = TEXT_COLORS.get(status, WHITE)))
        cursor += width + gap
  if not items:
    body.append(charts.text(left, CHART_TOP + 20, 'No rows surveyed yet',
                            fill = style['ink_secondary']))
  return charts.svg(CHART_WIDTH, height, body)


def alt_text(sections: List[Dict]) -> str:
  totals = total_counts(sections)
  groups = sum(1 for kind, _, _ in chart_items(sections) if kind == 'group')
  return (
    f"Stacked bars, one for each of {groups} feature groups, showing the "
    f"share of {sum(totals.values())} rows by CIR status: "
    + ', '.join(f"{totals[s]} {LABELS[s]}" for s in STATUSES[:-1])
    + f" and {totals[STATUSES[-1]]} {LABELS[STATUSES[-1]]}."
  )


def gap_rows(sections: List[Dict]) -> List[str]:
  '''The no and ignored rows, for the slide's presenter notes.'''
  lines = []
  for status in ('no', 'ignored'):
    for _, group in all_groups(sections):
      for row in group['rows']:
        if row['status'] == status:
          lines.append(f"{LABELS[status]}: {row['id']} | {row['feature']} "
                       f"| {row.get('planned') or '-'}")
  return lines


# Main ------------------------------------------------------------------


def rendered(sections: List[Dict], out_dir: Optional[Path]
             ) -> Dict[Path, str]:
  '''The three outputs, by path.'''
  if out_dir is None:
    paths = (HERE / 'support.md',
             ROOT / 'doc' / 'source' / 'cir_support.inc',
             HERE.parent / 'exsum' / 'support.svg')
  else:
    paths = (out_dir / 'support.md', out_dir / 'cir_support.inc',
             out_dir / 'support.svg')
  return {paths[0]: render_md(sections), paths[1]: render_inc(sections),
          paths[2]: render_svg(sections)}


def check(data_dir: Path, out_dir: Optional[Path], gate: str) -> int:
  report = Report()
  sections = load_sections(data_dir, report)
  check_data(sections, gate, report)
  if not report.errors:
    for path, content in rendered(sections, out_dir).items():
      current = path.read_text(encoding = 'utf-8') if path.exists() else None
      if current != content:
        report.error(str(path), 'is stale or missing; run make_support.py')
    print('\n'.join(format_counts(sections)))
  for message in report.warnings:
    print(f"warning: {message}", file = sys.stderr)
  for message in report.errors:
    print(f"error: {message}", file = sys.stderr)
  print(f"gate {gate}: {len(report.errors)} errors, "
        f"{len(report.warnings)} warnings")
  return 1 if report.errors else 0


def render(data_dir: Path, out_dir: Optional[Path]) -> int:
  report = Report()
  sections = load_sections(data_dir, report)
  check_data(sections, GATES[0], report)
  if report.errors:
    for message in report.errors:
      print(f"error: {message}", file = sys.stderr)
    print('not rendering: fix the data (make_support.py --check)',
          file = sys.stderr)
    return 1
  if out_dir is not None:
    out_dir.mkdir(parents = True, exist_ok = True)
  for path, content in rendered(sections, out_dir).items():
    path.write_text(content, encoding = 'utf-8')
    print(f"wrote {path}")
  print()
  print(f"alt text: {alt_text(sections)}")
  print()
  print('No and Ignored rows (id | feature | planned):')
  print('\n'.join(gap_rows(sections)) or '(none)')
  return 0


def main() -> int:
  parser = argparse.ArgumentParser(
    description = 'Render and check the CIR back end support table.'
  )
  parser.add_argument('--check', action = 'store_true',
                      help = 'validate instead of rendering')
  parser.add_argument('--gate', choices = GATES, default = GATES[0],
                      help = 'with --check, enforce the thresholds due by '
                             'this gate')
  parser.add_argument('--data-dir', type = Path, default = HERE,
                      help = 'the directory of the section files')
  parser.add_argument('--out-dir', type = Path, default = None,
                      help = 'write (or compare) the outputs here instead '
                             'of in the repository')
  args = parser.parse_args()
  if args.gate != GATES[0] and not args.check:
    parser.error('--gate needs --check')
  if args.check:
    return check(args.data_dir, args.out_dir, args.gate)
  return render(args.data_dir, args.out_dir)


if __name__ == '__main__':
  sys.exit(main())
